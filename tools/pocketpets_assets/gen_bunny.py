#!/usr/bin/env python3
"""Packs the Sticky Bunny rabbit sprites for Pocket Pets.

The artwork comes from limengdu/reTerminal_Sticky_Bunny (MIT License,
Copyright (c) 2026 limengdu); see src/pocketpets/third_party/STICKY_BUNNY_LICENSE.

Each sprite is trimmed to its drawing and stored as run-length rows:
one byte per run, top 2 bits = colour (0 clear, 1 white, 2 black),
low 6 bits = length - 1. A row table gives each row's start, so the device
can draw any row at any scale.

usage: gen_bunny.py <bunny repo> <output .cpp>
"""
import sys
from collections import deque
from pathlib import Path

from PIL import Image

# (symbol, file) in the order of the enum in BunnySprites.h
SPRITES = [
    ("EggIntact", "egg_intact"), ("EggCrackOne", "egg_crack_one"), ("EggCrackTwo", "egg_crack_two"),
    ("BabyIdle", "idle"), ("BabyFeed", "feed"), ("BabyPet", "pet"), ("BabyPlay", "play"),
    ("BabyHungry", "idle_hungry"), ("BabyTired", "idle_tired"),
    ("ChildIdle", "child_idle"), ("ChildFeed", "child_feed"), ("ChildPet", "child_pet"),
    ("ChildPlay", "child_play"), ("ChildHungry", "child_idle_hungry"), ("ChildTired", "child_idle_tired"),
]
for stage in ("youth", "adult"):
    for persona, tag in (("foodie", "Foodie"), ("affectionate", "Affectionate"), ("active", "Active")):
        for pose, ptag in (("idle", "Idle"), ("feed", "Feed"), ("pet", "Pet"), ("play", "Play")):
            SPRITES.append((f"{stage.capitalize()}{tag}{ptag}", f"{stage}_{persona}_{pose}"))


def load(path):
    im = Image.open(path).convert("L")
    w, h = im.size
    px = im.load()
    ink = [[px[x, y] < 128 for x in range(w)] for y in range(h)]
    # Background: white reachable from the border (same idea as the Bunny generator).
    bg = [[False] * w for _ in range(h)]
    q = deque()
    def push(x, y):
        if not bg[y][x] and not ink[y][x]:
            bg[y][x] = True
            q.append((x, y))
    for x in range(w):
        push(x, 0)
        push(x, h - 1)
    for y in range(h):
        push(0, y)
        push(w - 1, y)
    while q:
        x, y = q.popleft()
        for nx, ny in ((x - 1, y), (x + 1, y), (x, y - 1), (x, y + 1)):
            if 0 <= nx < w and 0 <= ny < h:
                push(nx, ny)
    color = [[0 if bg[y][x] else (2 if ink[y][x] else 1) for x in range(w)] for y in range(h)]
    # Trim to the drawing.
    rows = [y for y in range(h) if any(color[y])]
    cols = [x for x in range(w) if any(color[y][x] for y in range(h))]
    y0, y1, x0, x1 = rows[0], rows[-1], cols[0], cols[-1]
    return [row[x0:x1 + 1] for row in color[y0:y1 + 1]]


def encode(grid):
    data, offsets = bytearray(), []
    for row in grid:
        offsets.append(len(data))
        x = 0
        while x < len(row):
            c = row[x]
            n = 1
            while x + n < len(row) and row[x + n] == c and n < 64:
                n += 1
            data.append((c << 6) | (n - 1))
            x += n
    return data, offsets


def main():
    repo, out = Path(sys.argv[1]), Path(sys.argv[2])
    src = repo / "assets/desktop_pet/firmware"
    parts = ['// clang-format off', '// Generated by tools/pocketpets_assets/gen_bunny.py. Do not edit.',
             '// Rabbit artwork: reTerminal Sticky Bunny, MIT License, Copyright (c) 2026 limengdu.',
             '#include "BunnySprites.h"', '', 'namespace pp {', 'namespace {']
    table = []
    total = 0
    for sym, name in SPRITES:
        grid = load(src / f"{name}.png")
        data, offsets = encode(grid)
        h, w = len(grid), len(grid[0])
        total += len(data) + 2 * len(offsets)
        parts.append(f"const uint8_t k{sym}Data[] = {{{','.join(str(b) for b in data)}}};")
        parts.append(f"const uint16_t k{sym}Rows[] = {{{','.join(str(o) for o in offsets)}}};")
        table.append(f"    {{{w}, {h}, k{sym}Rows, k{sym}Data}},")
    parts.append('}  // namespace')
    parts.append('')
    parts.append('const Sprite BUNNY_SPRITES[static_cast<int>(BunnySprite::Count)] = {')
    parts.extend(table)
    parts.append('};')
    parts.append('')
    parts.append('}  // namespace pp')
    out.write_text("\n".join(parts) + "\n")
    print(f"{len(SPRITES)} sprites, {total} bytes")


if __name__ == "__main__":
    main()
